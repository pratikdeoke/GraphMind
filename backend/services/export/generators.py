"""
Export file generators.

Builds downloadable PDF (reportlab) and Excel (openpyxl) files for both
single-response exports and full memory exports.
"""

from datetime import datetime
from io import BytesIO
from typing import Any, Dict, List, Optional

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

# Theme colors (match GraphMind brand purple/blue).
BRAND_PURPLE = colors.HexColor("#6366F1")
BRAND_LIGHT = colors.HexColor("#EEF2FF")
HEADER_BLUE = "4472C4"
ALT_ROW_BLUE = "D9E2F3"
EXPORT_FOOTER = "Generated by GraphMind"


def export_filename(ext: str) -> str:
    """Canonical export filename, e.g. graphmind_export_2026-11-10.pdf."""
    return f"graphmind_export_{datetime.now().strftime('%Y-%m-%d')}.{ext}"


# ── PDF generation ───────────────────────────────────────────────────────────

def _pdf_styles() -> Dict[str, ParagraphStyle]:
    base = getSampleStyleSheet()
    return {
        "brand": ParagraphStyle(
            "BrandHeader", parent=base["Title"],
            textColor=BRAND_PURPLE, fontSize=22, spaceAfter=2,
        ),
        "meta": ParagraphStyle(
            "Meta", parent=base["Normal"],
            textColor=colors.grey, fontSize=9, spaceAfter=2,
        ),
        "title": ParagraphStyle(
            "DocTitle", parent=base["Heading2"],
            textColor=colors.HexColor("#1F2937"), fontSize=14,
            spaceBefore=12, spaceAfter=6,
        ),
        "section": ParagraphStyle(
            "Section", parent=base["Heading3"],
            textColor=BRAND_PURPLE, fontSize=12,
            spaceBefore=10, spaceAfter=4,
        ),
        "body": ParagraphStyle(
            "Body", parent=base["Normal"],
            textColor=colors.HexColor("#1F2937"), fontSize=10, leading=14,
            spaceAfter=6,
        ),
        "cell": ParagraphStyle(
            "Cell", parent=base["Normal"], fontSize=8, leading=10,
        ),
    }


def _footer(canvas, doc):
    """Page footer: 'Generated by GraphMind' + page number."""
    canvas.saveState()
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(colors.grey)
    canvas.drawCentredString(A4[0] / 2, 10 * mm,
                             f"{EXPORT_FOOTER}  |  Page {doc.page}")
    canvas.restoreState()


def _pdf_table(styles: Dict[str, ParagraphStyle],
               headers: List[str],
               rows: List[List[Any]]) -> Table:
    """Build a styled PDF table with wrapped cells."""
    cell_style = styles["cell"]
    data = [[Paragraph(f"<b>{h}</b>", cell_style) for h in headers]]
    for row in rows:
        data.append([Paragraph(str(cell) if cell not in (None, "") else "-",
                               cell_style) for cell in row])

    table = Table(data, repeatRows=1)
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), BRAND_PURPLE),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("ALIGN", (0, 0), (-1, -1), "LEFT"),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#CBD5E1")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1),
         [colors.white, BRAND_LIGHT]),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
    ]))
    return table


def generate_response_pdf(
    response_text: str,
    export_data: Optional[Dict[str, Any]],
    title: str,
    user_name: str,
) -> bytes:
    """Generate a formatted PDF for a single chat response export."""
    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer, pagesize=A4,
        topMargin=18 * mm, bottomMargin=18 * mm,
        leftMargin=16 * mm, rightMargin=16 * mm,
        title=title or "GraphMind Export",
    )
    styles = _pdf_styles()
    story: List[Any] = []

    # Header: brand + date + user.
    story.append(Paragraph("GraphMind", styles["brand"]))
    story.append(Paragraph(
        f"Exported on {datetime.now().strftime('%d %B %Y, %H:%M')}",
        styles["meta"]))
    story.append(Paragraph(f"User: {user_name}", styles["meta"]))
    story.append(Spacer(1, 8))

    # Title + response text as readable paragraphs.
    story.append(Paragraph(title or "Chat Response", styles["title"]))
    for paragraph in (response_text or "").strip().split("\n"):
        if paragraph.strip():
            story.append(Paragraph(paragraph.strip(), styles["body"]))

    # Optional table.
    if export_data and export_data.get("headers") and export_data.get("rows"):
        node_type = export_data.get("node_type") or "Data"
        story.append(Paragraph(f"{node_type} Details", styles["section"]))
        headers = export_data["headers"]
        rows = [[row.get(h, "") for h in headers]
                for row in export_data["rows"]]
        story.append(_pdf_table(styles, headers, rows))

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buffer.getvalue()


def generate_memory_pdf(
    sections: List[Dict[str, Any]],
    user_name: str,
    title: str = "Memory Export",
) -> bytes:
    """
    Generate a multi-section PDF of all user memory.

    Args:
        sections: [{"heading": "Stock Holdings", "headers": [...],
                    "rows": [[...], ...]}, ...]
    """
    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer, pagesize=A4,
        topMargin=18 * mm, bottomMargin=18 * mm,
        leftMargin=16 * mm, rightMargin=16 * mm,
        title=title,
    )
    styles = _pdf_styles()
    story: List[Any] = []

    story.append(Paragraph("GraphMind", styles["brand"]))
    story.append(Paragraph(
        f"{title} — {datetime.now().strftime('%d %B %Y, %H:%M')}",
        styles["meta"]))
    story.append(Paragraph(f"User: {user_name}", styles["meta"]))
    story.append(Spacer(1, 8))

    for section in sections:
        story.append(Paragraph(section["heading"], styles["title"]))
        headers = section.get("headers") or []
        rows = section.get("rows") or []
        if headers and rows:
            story.append(_pdf_table(styles, headers, rows))
        else:
            story.append(Paragraph("<i>No data available.</i>", styles["body"]))
        story.append(Spacer(1, 6))

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buffer.getvalue()


# ── Excel generation ─────────────────────────────────────────────────────────

def _write_sheet(ws, headers: List[str], rows: List[List[Any]],
                 sheet_title: str) -> None:
    """Write one styled sheet: blue header, alternating rows, sized columns."""
    ws.title = sheet_title[:31]  # Excel sheet name limit

    header_fill = PatternFill(start_color=HEADER_BLUE, end_color=HEADER_BLUE,
                              fill_type="solid")
    header_font = Font(color="FFFFFF", bold=True)
    alt_fill = PatternFill(start_color=ALT_ROW_BLUE, end_color=ALT_ROW_BLUE,
                           fill_type="solid")

    # Header row.
    for col, header in enumerate(headers, start=1):
        cell = ws.cell(row=1, column=col, value=header)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(horizontal="center", vertical="center")

    # Data rows with alternating background.
    numeric_columns: Dict[int, bool] = {}
    for row_idx, row in enumerate(rows, start=2):
        is_alt = row_idx % 2 == 0
        for col_idx, value in enumerate(row, start=1):
            cell = ws.cell(row=row_idx, column=col_idx, value=value)
            if is_alt:
                cell.fill = alt_fill
            if isinstance(value, (int, float)):
                numeric_columns[col_idx] = True

    # Summary row for numeric columns.
    if rows and numeric_columns:
        summary_row = len(rows) + 2
        ws.cell(row=summary_row, column=1, value="Total").font = Font(bold=True)
        for col_idx, is_numeric in numeric_columns.items():
            if not is_numeric:
                continue
            total = sum(
                row[col_idx - 1] for row in rows
                if isinstance(row[col_idx - 1], (int, float))
            )
            cell = ws.cell(row=summary_row, column=col_idx, value=total)
            cell.font = Font(bold=True)
            cell.number_format = "#,##0.00"

    # Auto-size columns.
    for col_idx, header in enumerate(headers, start=1):
        max_len = len(str(header))
        for row in rows:
            if col_idx - 1 < len(row):
                max_len = max(max_len, len(str(row[col_idx - 1] or "")))
        ws.column_dimensions[get_column_letter(col_idx)].width = \
            min(max_len + 4, 40)

    ws.freeze_panes = "A2"


def generate_response_excel(
    export_data: Dict[str, Any],
    title: str = "GraphMind Export",
) -> bytes:
    """Generate a single-sheet Excel for a structured chat response."""
    headers = export_data.get("headers") or []
    rows_data = export_data.get("rows") or []
    node_type = export_data.get("node_type") or "Data"

    rows = [[row.get(h, "") for h in headers] for row in rows_data]

    wb = Workbook()
    ws = wb.active
    sheet_title = f"{node_type} Holdings" if node_type in (
        "Stock", "MutualFund") else f"{node_type} Data"
    _write_sheet(ws, headers, rows, sheet_title)

    buffer = BytesIO()
    wb.save(buffer)
    return buffer.getvalue()


def generate_memory_excel(
    sheets: List[Dict[str, Any]],
    title: str = "Memory Export",
) -> bytes:
    """
    Generate a multi-sheet Excel of all user memory.

    Args:
        sheets: [{"title": "Stock Holdings", "headers": [...],
                  "rows": [[...], ...]}, ...]
    """
    wb = Workbook()
    wb.remove(wb.active)

    for idx, sheet in enumerate(sheets):
        ws = wb.create_sheet()
        _write_sheet(
            ws,
            sheet.get("headers") or [],
            sheet.get("rows") or [],
            sheet.get("title", f"Sheet {idx + 1}"),
        )

    buffer = BytesIO()
    wb.save(buffer)
    return buffer.getvalue()

